//! Complete enrollment assembly for deterministic in-process scenarios.
//! Protocol, trust, storage and disposal remain owned by their production APIs.
use std::sync::Arc;

use aura_app::runtime_bridge::{DeviceEnrollmentStart, RuntimeBridge};
use aura_core::effects::{PhysicalTimeEffects, ThresholdSigningEffects};
use aura_core::{AuthorityId, ContextId, TimeoutBudget};

use crate::core::{AgentConfig, AgentError, AgentResult};
use crate::handlers::invitation::{enrollment_manifest_admission, ShareableInvitation};
use crate::runtime_bridge::{AgentRuntimeBridge, OriginalIssuedEnrollmentContinuation};
use crate::{AuraAgent, SharedTransport};

type EnrollmentApp = Arc<async_lock::RwLock<aura_app::AppCore>>;

/// Replay inputs describe real isolated participants; they contain no signing material.
#[derive(Clone)]
pub struct EnrollmentParticipantProfile {
    /// Explicit isolated native profile configuration.
    pub config: AgentConfig,
    /// Initial participant authority; no signing authority is derived from this identifier.
    pub authority: AuthorityId,
    /// Original simulation context identifier.
    pub context: ContextId,
    /// Deterministic runtime entropy seed; protected records are generated by native owners.
    pub seed: u64,
}

/// One actual issuance and its original runtime/app/resource owners.
/// The recipient app is retained before import so host lifecycle tests use the
/// same public workflow owner rather than a fabricated completion.
pub struct SimulatedEnrollment {
    issuer: Arc<AuraAgent>,
    recipient: Arc<AuraAgent>,
    issuer_app: EnrollmentApp,
    recipient_app: EnrollmentApp,
    original: OriginalIssuedEnrollmentContinuation,
    profiles: [EnrollmentParticipantProfile; 2],
    clock: Arc<dyn PhysicalTimeEffects>,
    transport: SharedTransport,
    native_broker: bool,
    startup: TimeoutBudget,
    start: DeviceEnrollmentStart,
    invitation: crate::handlers::invitation::Invitation,
}

fn source_error(source: impl std::error::Error + Send + Sync + 'static) -> AgentError {
    aura_core::AuraError::Internal {
        message: "complete simulated enrollment lifecycle".into(),
        source: Some(Arc::new(source)),
    }
    .into()
}

/// A lifecycle failure preserves its primary source and each independent cleanup failure.
#[derive(Debug, thiserror::Error)]
#[error("simulated enrollment failed: {primary}; {cleanup_count} cleanup failures", cleanup_count = .cleanup.len())]
pub struct EnrollmentLifecycleFailure {
    #[source]
    primary: AgentError,
    cleanup: Vec<AgentError>,
    settled_execution_failure: Option<aura_core::AuraError>,
    cancellation_refusal: Option<aura_core::AuraError>,
    positive_disposal_acknowledged: bool,
}
impl EnrollmentLifecycleFailure {
    /// Original operation failure, preserved independently from cleanup.
    pub fn primary(&self) -> &AgentError {
        &self.primary
    }
    /// An original execution failure independently bound to its actual resource disposal.
    pub fn settled_execution_failure(&self) -> Option<&aura_core::AuraError> {
        self.settled_execution_failure.as_ref()
    }
    /// Actual raced canonical cancellation refusal, separately retained from resource cleanup.
    pub fn cancellation_refusal(&self) -> Option<&aura_core::AuraError> {
        self.cancellation_refusal.as_ref()
    }
    /// Observation that the original positive disposal was actually validated during cleanup.
    pub fn positive_disposal_acknowledged(&self) -> bool {
        self.positive_disposal_acknowledged
    }
    /// Independent cleanup failures; an empty slice is required for successful cleanup.
    pub fn cleanup_failures(&self) -> &[AgentError] {
        &self.cleanup
    }
}
async fn cleanup_agents(
    agents: &[Arc<AuraAgent>],
    clock: &Arc<dyn PhysicalTimeEffects>,
    startup: &TimeoutBudget,
) -> Vec<AgentError> {
    cleanup_agents_bound(agents, None, None, clock, startup).await
}
async fn cleanup_agents_bound(
    agents: &[Arc<AuraAgent>],
    original_disposal: Option<&crate::runtime_bridge::OriginalSimulationFailedDisposal>,
    cancellation_disposal: Option<
        &crate::runtime::services::ceremony_tracker::OriginalSimulationCancellationFailure,
    >,
    clock: &Arc<dyn PhysicalTimeEffects>,
    startup: &TimeoutBudget,
) -> Vec<AgentError> {
    let mut failures = Vec::new();
    for (index, agent) in agents.iter().enumerate() {
        if let Err(source) = agent
            .runtime()
            .tasks()
            .shutdown_with_original_budget(clock, startup)
            .await
        {
            let acknowledged_original_failure = if index == 0
                && cancellation_disposal.is_some_and(|actual| actual.matches_shutdown(&source))
            {
                true
            } else if index == 0 {
                match original_disposal {
                    Some(actual) => match actual.require_shutdown_failure(&source) {
                        Ok(()) => true,
                        Err(validation) => {
                            failures.push(validation.into());
                            false
                        }
                    },
                    None => false,
                }
            } else {
                false
            };
            if !acknowledged_original_failure {
                failures.push(source_error(source));
            }
        }
        if !agent.runtime().tasks().active_tasks().is_empty() {
            failures.push(AgentError::config(
                "enrollment cleanup retained actual owned tasks",
            ));
        }
    }
    failures
}
async fn fail_issued_with_cleanup(
    primary: AgentError,
    original: &OriginalIssuedEnrollmentContinuation,
    agents: &[Arc<AuraAgent>],
    clock: &Arc<dyn PhysicalTimeEffects>,
    startup: &TimeoutBudget,
    pending_gate: Option<(
        tokio::sync::oneshot::Sender<()>,
        tokio::sync::oneshot::Receiver<()>,
    )>,
) -> AgentError {
    let mut cleanup = Vec::new();
    let mut settled_execution_failure = None;
    let mut cancellation_disposal = None;
    let mut positive_disposal_acknowledged = false;
    match original
        .cancel_simulated_original(&agents[0], pending_gate)
        .await
    {
        Err(source) => cleanup.push(source),
        Ok(crate::handlers::invitation_service::OriginalSimulationCleanupOutcome::Committed) => {
            if let Err(source) = original.await_simulated_disposal(true).await {
                cleanup.push(source.into());
            } else {
                positive_disposal_acknowledged = true;
            }
        }
        Ok(crate::handlers::invitation_service::OriginalSimulationCleanupOutcome::Refused(
            actual,
        )) => {
            cancellation_disposal = Some(actual);
            match original.await_simulated_disposal(true).await {
                Ok(_) => positive_disposal_acknowledged = true,
                Err(source) => cleanup.push(source.into()),
            }
        }
        Ok(crate::handlers::invitation_service::OriginalSimulationCleanupOutcome::Cancelled) => {
            match original.observe_simulated_failed_disposal().await {
                Ok(actual) => settled_execution_failure = Some(actual),
                Err(source) => cleanup.push(source.into()),
            }
        }
    }
    cleanup.extend(
        cleanup_agents_bound(
            agents,
            settled_execution_failure.as_ref(),
            cancellation_disposal.as_ref(),
            clock,
            startup,
        )
        .await,
    );
    source_error(EnrollmentLifecycleFailure {
        primary,
        cleanup,
        cancellation_refusal: cancellation_disposal
            .as_ref()
            .map(|actual| actual.source().clone()),
        positive_disposal_acknowledged,
        settled_execution_failure: settled_execution_failure
            .as_ref()
            .map(|actual| actual.native().clone()),
    })
}
async fn fail_with_cleanup(
    primary: AgentError,
    agents: &[Arc<AuraAgent>],
    clock: &Arc<dyn PhysicalTimeEffects>,
    startup: &TimeoutBudget,
) -> AgentError {
    let cleanup = cleanup_agents(agents, clock, startup).await;
    source_error(EnrollmentLifecycleFailure {
        primary,
        cleanup,
        settled_execution_failure: None,
        cancellation_refusal: None,
        positive_disposal_acknowledged: false,
    })
}
async fn assemble(
    profile: &EnrollmentParticipantProfile,
    clock: Arc<dyn PhysicalTimeEffects>,
    transport: SharedTransport,
    startup: &TimeoutBudget,
    native_broker: bool,
) -> AgentResult<Arc<AuraAgent>> {
    let context = aura_core::context::EffectContext::new(
        profile.authority,
        profile.context,
        if native_broker {
            aura_core::effects::ExecutionMode::Testing
        } else {
            aura_core::effects::ExecutionMode::Simulation { seed: profile.seed }
        },
    );
    let agent = if native_broker {
        let owner =
            crate::runtime::builder::TestingOwnedProfileCapability::acquire(&profile.config)?;
        let mut builder = crate::runtime::EffectSystemBuilder::testing_with_owned_profile(owner)
            .with_authority(profile.authority)
            .with_config(profile.config.clone())
            .with_physical_time_provider(clock.clone())
            .with_sync_config(Default::default());
        if profile.config.bootstrap_broker.enabled {
            builder = builder.with_rendezvous_config(profile.config.rendezvous_config());
        }
        Arc::new(AuraAgent::new(
            builder.build(&context).await.map_err(AgentError::from)?,
            profile.authority,
        ))
    } else {
        let mut builder = crate::core::AgentBuilder::new()
            .with_authority(profile.authority)
            .with_config(profile.config.clone())
            .with_physical_time_provider(clock.clone());
        if profile.config.bootstrap_broker.enabled {
            builder = builder.with_rendezvous_config(profile.config.rendezvous_config());
        }
        Arc::new(
            builder
                .build_simulation_async_with_shared_transport(profile.seed, &context, transport)
                .await?,
        )
    };
    let initialized = async {
        if agent.runtime().effects().config().storage.base_path != profile.config.storage.base_path
        {
            return Err(AgentError::config(
                "complete lifecycle requires an explicit unchanged profile path",
            ));
        }
        AgentRuntimeBridge::new(agent.clone())
            .bootstrap_signing_keys(startup)
            .await
            .map_err(source_error)
    }
    .await;
    if let Err(primary) = initialized {
        return Err(
            fail_with_cleanup(primary, std::slice::from_ref(&agent), &clock, startup).await,
        );
    }
    Ok(agent)
}

fn app(agent: Arc<AuraAgent>) -> AgentResult<EnrollmentApp> {
    Ok(Arc::new(async_lock::RwLock::new(
        aura_app::AppCore::with_runtime(
            aura_app::AppConfig::default(),
            Arc::new(AgentRuntimeBridge::new(agent)),
        )
        .map_err(source_error)?,
    )))
}

impl SimulatedEnrollment {
    /// Assemble native profile owners, export setup and explicitly transfer the
    /// independent pin before canonical original issuer registration.
    pub async fn prepare(
        profiles: [EnrollmentParticipantProfile; 2],
        clock: Arc<dyn PhysicalTimeEffects>,
        transport: SharedTransport,
        startup: TimeoutBudget,
    ) -> AgentResult<Self> {
        Self::prepare_with_mode(profiles, clock, transport, startup, false).await
    }

    /// Reuse the complete signed lifecycle with the native guarded transport.
    /// Both participants must explicitly opt into the development broker; the
    /// production default remains disabled. This fixture mode cannot silently
    /// fall back to the simulation inbox for the original first frame.
    pub async fn prepare_native_broker(
        profiles: [EnrollmentParticipantProfile; 2],
        clock: Arc<dyn PhysicalTimeEffects>,
        transport: SharedTransport,
        startup: TimeoutBudget,
    ) -> AgentResult<Self> {
        if profiles
            .iter()
            .any(|profile| !profile.config.bootstrap_broker.enabled)
        {
            return Err(AgentError::config(
                "native broker fixture requires both exact participants",
            ));
        }
        Self::prepare_with_mode(profiles, clock, transport, startup, true).await
    }

    async fn prepare_with_mode(
        profiles: [EnrollmentParticipantProfile; 2],
        clock: Arc<dyn PhysicalTimeEffects>,
        transport: SharedTransport,
        startup: TimeoutBudget,
        native_broker: bool,
    ) -> AgentResult<Self> {
        let mut acquired = Vec::new();
        let mut issued_owner = None;
        let result = async {
            let issuer = assemble(
                &profiles[0],
                clock.clone(),
                transport.clone(),
                &startup,
                native_broker,
            )
            .await?;
            acquired.push(issuer.clone());
            let recipient = assemble(
                &profiles[1],
                clock.clone(),
                transport.clone(),
                &startup,
                native_broker,
            )
            .await?;
            acquired.push(recipient.clone());
            let issuer_app = app(issuer.clone())?;
            let recipient_app = app(recipient.clone())?;
            let code = AgentRuntimeBridge::new(recipient.clone())
                .export_device_enrollment_setup_request()
                .await
                .map_err(source_error)?;
            let pin =
                aura_app::ui::workflows::ceremonies::pin_user_transferred_device_enrollment_setup(
                    &issuer_app,
                    code,
                )
                .await
                .map_err(source_error)?;
            let (start, original) = AgentRuntimeBridge::new(issuer.clone())
                .issue_original_device_enrollment_owned("Simulated device".into(), pin)
                .await
                .map_err(source_error)?;
            issued_owner = Some(original);
            let decoded =
                ShareableInvitation::from_code(&start.enrollment_code).map_err(source_error)?;
            let invitation = issuer
                .invitations()?
                .get(&decoded.invitation_id)
                .await
                .ok_or_else(|| {
                    AgentError::from(aura_core::AuraError::permission_denied(
                        "original simulated enrollment invitation is missing",
                    ))
                })?;
            Ok(Self {
                issuer,
                recipient,
                issuer_app,
                recipient_app,
                original: issued_owner
                    .take()
                    .expect("actual original issuance retained"),
                profiles,
                clock: clock.clone(),
                transport,
                native_broker,
                startup: startup.clone(),
                start,
                invitation,
            })
        }
        .await;
        match result {
            Ok(actual) => Ok(actual),
            Err(primary) => match issued_owner.as_ref() {
                Some(original) => Err(fail_issued_with_cleanup(
                    primary, original, &acquired, &clock, &startup, None,
                )
                .await),
                None => Err(fail_with_cleanup(primary, &acquired, &clock, &startup).await),
            },
        }
    }

    /// The same runtime-backed recipient AppCore retained before import.
    pub fn recipient_app(&self) -> EnrollmentApp {
        self.recipient_app.clone()
    }
    /// The actual isolated issuer runtime.
    pub fn issuer(&self) -> &Arc<AuraAgent> {
        &self.issuer
    }
    /// The actual isolated recipient runtime.
    pub fn recipient(&self) -> &Arc<AuraAgent> {
        &self.recipient
    }
    /// The original signed issuance transfer, without reconstructed execution authority.
    pub fn start(&self) -> &DeviceEnrollmentStart {
        &self.start
    }
    /// Read-only selector retained by the original signed issuer owner.
    pub fn original_mailbox_selector(
        &self,
    ) -> Option<(AuthorityId, aura_core::DeviceId, [u8; 32])> {
        let session = aura_invitation::enrollment_mailbox_session::original_enrollment_session_id(
            &self.invitation.invitation_id,
        );
        self.issuer
            .runtime()
            .effects()
            .original_mailbox_issuer(session)
            .map(|retained| {
                (
                    retained.manifest().subject,
                    retained.manifest().invitee_device,
                    retained.digest(),
                )
            })
    }
    /// The original selected physical-time provider.
    pub fn selected_clock(&self) -> &Arc<dyn PhysicalTimeEffects> {
        &self.clock
    }
    /// The caller-selected startup endpoint shared with reopen.
    pub fn original_startup_window(&self) -> &TimeoutBudget {
        &self.startup
    }

    /// Canonical explicit manifest transfer and import; app-owner scenarios may
    /// instead perform this through the public workflow on recipient_app().
    #[aura_macros::capability_boundary(category = "capability_gated", capability = "SimulatedEnrollment", receiver_type = SimulatedEnrollment, family = "runtime_helper")]
    pub async fn import_recipient(&self) -> AgentResult<()> {
        let transfer = self.start.manifest_transfer.as_ref().ok_or_else(|| {
            AgentError::config("original issuer did not export its manifest transfer")
        })?;
        let pin = aura_app::ui::workflows::ceremonies::pin_user_transferred_enrollment_manifest(
            &self.recipient_app,
            transfer.manifest_code.clone(),
            transfer.initiator_verifier_code.clone(),
        )
        .await
        .map_err(source_error)?;
        AgentRuntimeBridge::new(self.recipient.clone())
            .import_enrollment_invitation(&self.start.enrollment_code, pin)
            .await
            .map_err(source_error)?;
        Ok(())
    }

    /// Complete canonical native acceptance while retaining this lifecycle owner
    /// for subsequent host success or failure settlement.
    #[aura_macros::capability_boundary(category = "capability_gated", capability = "SimulatedEnrollment", receiver_type = SimulatedEnrollment, family = "runtime_helper")]
    pub async fn accept_recipient(&self) -> AgentResult<()> {
        self.import_recipient().await?;
        AgentRuntimeBridge::new(self.recipient.clone())
            .accept_invitation(&self.invitation.invitation_id.to_string())
            .await
            .map(|_| ())
            .map_err(source_error)
    }

    #[aura_macros::capability_boundary(category = "capability_gated", capability = "SimulatedEnrollment", receiver_type = SimulatedEnrollment, family = "runtime_helper")]
    /// Import and accept through the canonical runtime bridge, then strictly dispose.
    pub async fn accept(self) -> AgentResult<StoppedEnrollmentProfiles> {
        let result = self.accept_recipient().await;
        if let Err(primary) = result {
            return Err(self.fail(primary).await);
        }
        self.finish_accepted().await
    }

    /// Observe an actual external app completion, without constructing one.
    #[aura_macros::capability_boundary(category = "capability_gated", capability = "SimulatedEnrollment", receiver_type = SimulatedEnrollment, family = "runtime_helper")]
    pub async fn finish_accepted(self) -> AgentResult<StoppedEnrollmentProfiles> {
        self.finish_accepted_with_host_failure(None).await
    }

    async fn finish_accepted_with_host_failure(
        self,
        expected_host_failure: Option<&AgentError>,
    ) -> AgentResult<StoppedEnrollmentProfiles> {
        let result = async {
            let confirmed = enrollment_manifest_admission::load_confirmed_enrollment(
                self.recipient.runtime().effects().as_ref(),
                self.profiles[1].authority,
                &self.invitation.invitation_id,
            )
            .await?;
            let subject = confirmed.confirmation().manifest().subject;
            let digest = confirmed.confirmation().manifest_digest();
            let package = self
                .recipient
                .runtime()
                .threshold_signing()
                .public_key_package(&subject)
                .await
                .ok_or_else(|| {
                    AgentError::config("confirmed participant has no active public package")
                })?;
            self.original.await_simulated_disposal(true).await?;
            Ok::<_, AgentError>((subject, digest, package))
        }
        .await;
        match result {
            Ok((subject, digest, package)) => {
                self.shutdown(
                    EnrollmentDisposition::Accepted {
                        subject,
                        digest,
                        package,
                    },
                    expected_host_failure,
                )
                .await
            }
            Err(primary) => Err(self.fail(primary).await),
        }
    }

    /// Preserve an app/host failure after native acceptance while validating
    /// the original positive disposal and returning the same stopped profiles
    /// for independent durable reopen. This never publishes semantic success.
    #[aura_macros::capability_boundary(category = "capability_gated", capability = "SimulatedEnrollment", receiver_type = SimulatedEnrollment, family = "runtime_helper")]
    pub async fn settle_accepted_host_failure(
        self,
        primary: AgentError,
    ) -> AgentResult<(AgentError, StoppedEnrollmentProfiles)> {
        match self.finish_accepted_with_host_failure(Some(&primary)).await {
            Ok(stopped) => Ok((
                source_error(EnrollmentLifecycleFailure {
                    primary,
                    cleanup: Vec::new(),
                    settled_execution_failure: None,
                    cancellation_refusal: None,
                    positive_disposal_acknowledged: true,
                }),
                stopped,
            )),
            Err(cleanup) => Err(source_error(EnrollmentLifecycleFailure {
                primary,
                cleanup: vec![cleanup],
                settled_execution_failure: None,
                cancellation_refusal: None,
                positive_disposal_acknowledged: false,
            })),
        }
    }

    #[aura_macros::capability_boundary(category = "capability_gated", capability = "SimulatedEnrollment", receiver_type = SimulatedEnrollment, family = "runtime_helper")]
    /// Import and reject through the native protocol, preserving its failure and resource disposal.
    pub async fn reject(self) -> AgentResult<StoppedEnrollmentProfiles> {
        let result = async {
            self.import_recipient().await?;
            self.recipient
                .invitations()?
                .decline(&self.invitation.invitation_id)
                .await?;
            let native = self
                .original
                .await_simulated_disposal(false)
                .await?
                .ok_or_else(|| {
                    AgentError::config("rejection did not preserve its execution failure")
                })?;
            let mut current: Option<&(dyn std::error::Error + 'static)> = Some(&native);
            let mut rejected = false;
            while let Some(source) = current {
                rejected |= matches!(
                    source
                        .downcast_ref::<crate::handlers::invitation::EnrollmentVmAdmissionError>(),
                    Some(
                        crate::handlers::invitation::EnrollmentVmAdmissionError::TerminalFailed(
                            aura_app::runtime_bridge::CeremonyFailureReason::Rejected
                        )
                    )
                );
                current = source.source();
            }
            if !rejected {
                return Err(AgentError::from(native));
            }
            Ok::<_, AgentError>(native)
        }
        .await;
        match result {
            Ok(native) => {
                self.shutdown(EnrollmentDisposition::Rejected { source: native }, None)
                    .await
            }
            Err(primary) => Err(self.fail(primary).await),
        }
    }

    /// Finish an externally failed app attempt through the same retained runtimes.
    #[aura_macros::capability_boundary(category = "capability_gated", capability = "SimulatedEnrollment", receiver_type = SimulatedEnrollment, family = "runtime_helper")]
    pub async fn fail(self, primary: AgentError) -> AgentError {
        fail_issued_with_cleanup(
            primary,
            &self.original,
            &[self.issuer.clone(), self.recipient.clone()],
            &self.clock,
            &self.startup,
            None,
        )
        .await
    }

    /// Deterministically suspend cleanup after its actual original Pending
    /// observation, allowing a competing canonical decision to finish first.
    #[aura_macros::capability_boundary(category = "capability_gated", capability = "SimulatedEnrollment", receiver_type = SimulatedEnrollment, family = "runtime_helper")]
    pub async fn fail_after_pending_observation(
        self,
        primary: AgentError,
        entered: tokio::sync::oneshot::Sender<()>,
        release: tokio::sync::oneshot::Receiver<()>,
    ) -> AgentError {
        fail_issued_with_cleanup(
            primary,
            &self.original,
            &[self.issuer.clone(), self.recipient.clone()],
            &self.clock,
            &self.startup,
            Some((entered, release)),
        )
        .await
    }

    async fn shutdown(
        self,
        disposition: EnrollmentDisposition,
        expected_host_failure: Option<&AgentError>,
    ) -> AgentResult<StoppedEnrollmentProfiles> {
        fn matches_original_host_failure(
            failure: &crate::task_registry::TaskSupervisionError,
            primary: &AgentError,
        ) -> bool {
            use aura_core::effects::task::{RequiredTaskExit, RequiredTaskTerminalFailure};
            use std::error::Error;
            let crate::task_registry::TaskSupervisionError::TaskFailed {
                group,
                task,
                source,
            } = failure
            else {
                return false;
            };
            if group != "runtime" || task != "app.enrollment_import" {
                return false;
            }
            let mut cause: Option<&(dyn Error + 'static)> = Some(source);
            let mut terminal = None;
            while let Some(error) = cause {
                if let Some(actual) = error.downcast_ref::<RequiredTaskTerminalFailure>() {
                    terminal = Some(actual);
                    break;
                }
                cause = error.source();
            }
            let Some(terminal) = terminal else {
                return false;
            };
            let RequiredTaskExit::Failed(execution) = terminal.execution() else {
                return false;
            };
            // Cloned AuraError envelopes retain the same native host source.
            // Equal text or error category never suffices to dismiss a task.
            let primary_source = primary.source().and_then(Error::source);
            matches!(
                (primary_source, execution.source(), terminal.terminal().source()),
                (Some(a), Some(b), Some(c)) if std::ptr::eq(a, b) && std::ptr::eq(a, c)
            )
        }
        let issuer_result = self
            .issuer
            .runtime()
            .tasks()
            .shutdown_with_original_budget(&self.clock, &self.startup)
            .await;
        let recipient_result = self
            .recipient
            .runtime()
            .tasks()
            .shutdown_with_original_budget(&self.clock, &self.startup)
            .await;
        let issuer_validation = (|| {
            match (&disposition, issuer_result) {
                (EnrollmentDisposition::Accepted { .. }, Ok(())) => {}
                (
                    EnrollmentDisposition::Rejected { source: native },
                    Err(crate::task_registry::TaskSupervisionError::TaskFailed { source, .. }),
                ) => {
                    // Both actual boundaries must retain the same original native allocation.
                    fn find_native<'a>(
                        source: &'a (dyn std::error::Error + 'static),
                    ) -> Option<&'a crate::handlers::invitation::EnrollmentVmAdmissionError>
                    {
                        let mut current = Some(source);
                        while let Some(actual) = current {
                            if let Some(actual) = actual.downcast_ref() {
                                return Some(actual);
                            }
                            current = actual.source();
                        }
                        None
                    }
                    if !matches!((find_native(native), find_native(&source)), (Some(a), Some(b)) if std::ptr::eq(a,b))
                    {
                        return Err(AgentError::from(source));
                    }
                }
                (_, Err(source)) => return Err(source_error(source)),
                _ => {
                    return Err(AgentError::config(
                        "rejected lifecycle lost its typed task failure",
                    ))
                }
            }
            Ok::<_, AgentError>(())
        })();
        let mut failures = Vec::new();
        if let Err(source) = issuer_validation {
            failures.push(source);
        }
        if let Err(source) = recipient_result {
            if !expected_host_failure
                .is_some_and(|primary| matches_original_host_failure(&source, primary))
            {
                failures.push(source_error(source));
            }
        }
        if !self.issuer.runtime().tasks().active_tasks().is_empty()
            || !self.recipient.runtime().tasks().active_tasks().is_empty()
        {
            failures.push(AgentError::config(
                "complete enrollment retained live owned tasks after shutdown",
            ));
        }
        if !failures.is_empty() {
            let primary = failures.remove(0);
            return Err(source_error(EnrollmentLifecycleFailure {
                primary,
                cleanup: failures,
                settled_execution_failure: None,
                cancellation_refusal: None,
                positive_disposal_acknowledged: false,
            }));
        }
        let Self {
            issuer,
            recipient,
            issuer_app,
            recipient_app,
            original,
            profiles,
            clock,
            transport,
            native_broker,
            startup,
            start,
            invitation,
        } = self;
        drop((
            issuer_app,
            recipient_app,
            original,
            issuer,
            recipient,
            transport,
        ));
        Ok(StoppedEnrollmentProfiles {
            profiles,
            clock,
            native_broker,
            startup,
            start,
            invitation,
            disposition,
        })
    }
}

/// Durable observations survive resource shutdown; no runtime capability is
/// reconstructed from these fields. Reopen revalidates protected native evidence.
pub struct StoppedEnrollmentProfiles {
    profiles: [EnrollmentParticipantProfile; 2],
    clock: Arc<dyn PhysicalTimeEffects>,
    native_broker: bool,
    startup: TimeoutBudget,
    start: DeviceEnrollmentStart,
    invitation: crate::handlers::invitation::Invitation,
    disposition: EnrollmentDisposition,
}

enum EnrollmentDisposition {
    Accepted {
        subject: AuthorityId,
        digest: [u8; 32],
        package: Vec<u8>,
    },
    Rejected {
        source: aura_core::AuraError,
    },
}

/// Reopened, authenticated native profiles retained for one new app host
/// recovery operation. Dropping this owner is not a shutdown acknowledgment.
pub struct ReopenedEnrollment {
    agents: [Arc<AuraAgent>; 2],
    recipient_app: EnrollmentApp,
    clock: Arc<dyn PhysicalTimeEffects>,
    startup: TimeoutBudget,
}
impl ReopenedEnrollment {
    pub fn recipient_app(&self) -> EnrollmentApp {
        self.recipient_app.clone()
    }

    pub fn recipient(&self) -> &Arc<AuraAgent> {
        &self.agents[1]
    }

    pub async fn shutdown(self) -> AgentResult<()> {
        let mut failures = cleanup_agents(&self.agents, &self.clock, &self.startup).await;
        if failures.is_empty() {
            Ok(())
        } else {
            Err(source_error(EnrollmentLifecycleFailure {
                primary: failures.remove(0),
                cleanup: failures,
                settled_execution_failure: None,
                cancellation_refusal: None,
                positive_disposal_acknowledged: false,
            }))
        }
    }
}

impl StoppedEnrollmentProfiles {
    /// Reopen the accepted original profiles and retain actual runtime owners
    /// while the app retries host persistence under a fresh semantic instance.
    pub async fn reopen_accepted_for_host_recovery(
        self,
        transport: SharedTransport,
    ) -> AgentResult<ReopenedEnrollment> {
        let EnrollmentDisposition::Accepted {
            subject,
            digest,
            package,
        } = &self.disposition
        else {
            return Err(AgentError::config(
                "rejected enrollment cannot recover host storage",
            ));
        };
        let mut recipient_profile = self.profiles[1].clone();
        recipient_profile.authority = *subject;
        let mut acquired = Vec::new();
        let result = async {
            let issuer = assemble(
                &self.profiles[0],
                self.clock.clone(),
                transport.clone(),
                &self.startup,
                self.native_broker,
            )
            .await?;
            acquired.push(issuer.clone());
            let recipient = assemble(
                &recipient_profile,
                self.clock.clone(),
                transport,
                &self.startup,
                self.native_broker,
            )
            .await?;
            acquired.push(recipient.clone());
            let confirmed = enrollment_manifest_admission::load_confirmed_enrollment(
                recipient.runtime().effects().as_ref(),
                self.profiles[1].authority,
                &self.invitation.invitation_id,
            )
            .await?;
            if confirmed.confirmation().manifest_digest() != *digest
                || recipient
                    .runtime()
                    .effects()
                    .public_key_package(subject)
                    .await
                    .as_ref()
                    != Some(package)
            {
                return Err(AgentError::config("same-profile confirmed package changed"));
            }
            let recipient_app = app(recipient.clone())?;
            Ok::<_, AgentError>((issuer, recipient, recipient_app))
        }
        .await;
        match result {
            Ok((issuer, recipient, recipient_app)) => Ok(ReopenedEnrollment {
                agents: [issuer, recipient],
                recipient_app,
                clock: self.clock,
                startup: self.startup,
            }),
            Err(primary) => {
                Err(fail_with_cleanup(primary, &acquired, &self.clock, &self.startup).await)
            }
        }
    }
    /// The retained native rejection source, if this lifecycle rejected.
    pub fn rejected_source(&self) -> Option<&aura_core::AuraError> {
        match &self.disposition {
            EnrollmentDisposition::Rejected { source } => Some(source),
            _ => None,
        }
    }

    /// Reopen both actual profiles under the same provider and original startup
    /// endpoint. A completed recipient adopts only its authenticated subject.
    #[aura_macros::capability_boundary(category = "capability_gated", capability = "StoppedEnrollmentProfiles", receiver_type = StoppedEnrollmentProfiles, family = "runtime_helper")]
    pub async fn reopen_and_shutdown(self, transport: SharedTransport) -> AgentResult<()> {
        let mut recipient_profile = self.profiles[1].clone();
        if let EnrollmentDisposition::Accepted { subject, .. } = &self.disposition {
            recipient_profile.authority = *subject;
        }
        let mut acquired = Vec::new();
        let result = async {
            let issuer = assemble(
                &self.profiles[0],
                self.clock.clone(),
                transport.clone(),
                &self.startup,
                self.native_broker,
            )
            .await?;
            acquired.push(issuer.clone());
            let recipient = assemble(
                &recipient_profile,
                self.clock.clone(),
                transport,
                &self.startup,
                self.native_broker,
            )
            .await?;
            acquired.push(recipient.clone());
            match &self.disposition {
                EnrollmentDisposition::Accepted {
                    digest,
                    package,
                    subject,
                } => {
                    let confirmed = enrollment_manifest_admission::load_confirmed_enrollment(
                        recipient.runtime().effects().as_ref(),
                        self.profiles[1].authority,
                        &self.invitation.invitation_id,
                    )
                    .await?;
                    if confirmed.confirmation().manifest_digest() != *digest
                        || recipient
                            .runtime()
                            .effects()
                            .public_key_package(subject)
                            .await
                            .as_ref()
                            != Some(package)
                    {
                        return Err(AgentError::config(
                            "same-profile confirmation or active package changed",
                        ));
                    }
                }
                EnrollmentDisposition::Rejected { .. } => {
                    let outcome = issuer
                        .runtime()
                        .ceremony_runner()
                        .terminal_outcome(&self.start.ceremony_id)
                        .await?;
                    if outcome
                        != Some(aura_app::runtime_bridge::CeremonyTerminalOutcome::Failed(
                            aura_app::runtime_bridge::CeremonyFailureReason::Rejected,
                        ))
                    {
                        return Err(AgentError::config(
                            "same-profile original rejection changed",
                        ));
                    }
                }
            }
            Ok::<_, AgentError>(())
        }
        .await;
        match result {
            Err(primary) => {
                Err(fail_with_cleanup(primary, &acquired, &self.clock, &self.startup).await)
            }
            Ok(()) => {
                let mut cleanup = cleanup_agents(&acquired, &self.clock, &self.startup).await;
                if cleanup.is_empty() {
                    Ok(())
                } else {
                    let primary = cleanup.remove(0);
                    Err(source_error(EnrollmentLifecycleFailure {
                        primary,
                        cleanup,
                        settled_execution_failure: None,
                        cancellation_refusal: None,
                        positive_disposal_acknowledged: false,
                    }))
                }
            }
        }
    }
}
